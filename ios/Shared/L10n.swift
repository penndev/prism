    static func t(_ key: String, language: String, args: [CVarArg] = []) -> String {
        let table = table(for: language)
        let format = table[key] ?? en[key] ?? key
        if args.isEmpty { return format }
        return String(format: format, arguments: args)
    }

    static func raw(_ key: String, args: [CVarArg] = []) -> String {
        t(key, language: Prefs().loadSettings().system.language, args: args)
    }

    static func table(for language: String) -> [String: String] {
        let tag: String
        if language.isEmpty || language == languageSystem {
            let pref = Locale.preferredLanguages.first ?? "en"
            tag = pref.lowercased().hasPrefix("zh") ? "zh-CN" : "en"
        } else {
            tag = language
        }
        return tag == "zh-CN" ? zh : en
    }

